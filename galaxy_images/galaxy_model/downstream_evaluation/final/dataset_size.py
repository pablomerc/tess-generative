"""
Report dataset sizes and source counts for downstream evaluation datasets.

This script examines the data sources used in:
  - baseline_all.py (Neighbors dataset)
  - predict.py (downstream_dataset.h5)

Run from galaxy_model/ or downstream_evaluation/final/:
  python downstream_evaluation/final/dataset_size.py
"""
import sys
from pathlib import Path

_here = Path(__file__).resolve().parent
_src = _here.parent.parent
if str(_src) not in sys.path:
    sys.path.insert(0, str(_src))

import h5py
import numpy as np
from prepare_all import (
    NEIGHBORS_HDF5,
    NUM_EXAMPLES_NEIGHBORS,
    NEIGHBORS_SEED,
    SHUFFLE_NEIGHBORS,
)


def analyze_neighbors_dataset():
    """Analyze the Neighbors dataset used by baseline_all.py"""
    print("="*80)
    print("NEIGHBORS DATASET (used by baseline_all.py)")
    print("="*80)
    print(f"File: {NEIGHBORS_HDF5}")
    print(f"Config: NUM_EXAMPLES_NEIGHBORS = {NUM_EXAMPLES_NEIGHBORS}")
    print(f"        SHUFFLE_NEIGHBORS = {SHUFFLE_NEIGHBORS}")
    print(f"        NEIGHBORS_SEED = {NEIGHBORS_SEED}")
    print()
    
    with h5py.File(NEIGHBORS_HDF5, "r") as f:
        sources = f["source_type"][:]
        print(f"Total samples in file: {len(sources)}")
        
        unique_sources, counts = np.unique(sources, return_counts=True)
        print("\nSamples by source_type:")
        for src, count in zip(unique_sources, counts):
            print(f"  source_type {src}: {count:,} samples")
        
        indexes_mmu = np.where(sources == 0)[0]
        n_total = len(indexes_mmu)
        n_use = min(NUM_EXAMPLES_NEIGHBORS, n_total)
        
        print(f"\nFiltering for source_type == 0 (MMU):")
        print(f"  Total MMU samples: {n_total:,}")
        print(f"  Used (min(NUM_EXAMPLES_NEIGHBORS, n_total)): {n_use:,}")
        
        if SHUFFLE_NEIGHBORS:
            print(f"\nNote: Samples are shuffled with seed={NEIGHBORS_SEED}")
            print(f"      So the actual {n_use:,} samples used are a shuffled subset")
        else:
            print(f"\nNote: Samples are NOT shuffled")
            print(f"      So the first {n_use:,} MMU samples are used")
    
    print()


def analyze_downstream_dataset():
    """Analyze the downstream_dataset.h5 used by predict.py"""
    print("="*80)
    print("DOWNSTREAM_DATASET.H5 (used by predict.py)")
    print("="*80)
    
    dataset_path = _here.parent / "downstream_dataset.h5"
    print(f"File: {dataset_path}")
    
    if not dataset_path.exists():
        print("ERROR: File not found!")
        print("This file should be generated by a prepare script.")
        return
    
    print()
    with h5py.File(dataset_path, "r") as f:
        print("Datasets in file:")
        for key in f.keys():
            if isinstance(f[key], h5py.Dataset):
                print(f"  {key}: shape {f[key].shape}, dtype {f[key].dtype}")
        
        if "embeddings_1" in f and "embeddings_2" in f:
            n_samples = len(f["embeddings_1"])
            print(f"\nTotal samples: {n_samples:,}")
            
            print("\nBased on predict.py comment:")
            print("  Indices 0-8191 are HSC: 8,192 samples")
            print("  Indices 8192-16383 are Legacy: 8,192 samples")
            
            print("\npredict.py default configuration:")
            print("  sample_start_idx = 0")
            print("  sample_end_idx = 8192")
            print("  => Uses HSC samples only (indices 0-8191)")
            
            print("\nMetadata fields:")
            if "metadata" in f:
                print(f"  metadata: shape {f['metadata'].shape}")
            if "param_names" in f:
                param_names = [name.decode('utf-8') for name in f['param_names'][:]]
                print(f"  param_names: {len(param_names)} parameters")
                print(f"    First 5: {param_names[:5]}")
    
    print()


def main():
    print("\n")
    print("#" * 80)
    print("# DATASET SIZE ANALYSIS")
    print("#" * 80)
    print()
    
    analyze_neighbors_dataset()
    analyze_downstream_dataset()
    
    print("="*80)
    print("SUMMARY")
    print("="*80)
    print()
    print("baseline_all.py uses:")
    print("  - Neighbors dataset (NEIGHBORS_HDF5)")
    print("  - Filters for source_type == 0 (MMU sources)")
    print(f"  - Takes up to {NUM_EXAMPLES_NEIGHBORS:,} samples")
    print()
    print("predict.py uses:")
    print("  - downstream_dataset.h5")
    print("  - Default: indices 0-8191 (HSC samples)")
    print("  - Can be configured via sample_start_idx and sample_end_idx")
    print()


if __name__ == "__main__":
    main()
